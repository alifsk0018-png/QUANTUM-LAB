export const GATE_LIST = Object.values(GATE_CATALOG);

export function createDefaultGate(gateName, primaryQubit = 0, numQubits = 2) {
  const canonical = gateName.toUpperCase() === 'CNOT' ? 'CX' : gateName.toUpperCase();
  const meta = GATE_CATALOG[canonical];
  if (!meta) return null;

  const available = Array.from({ length: numQubits }, (_, i) => i);
  const q0 = Math.min(Math.max(0, primaryQubit), numQubits - 1);
  const others = available.filter((q) => q !== q0);

  let target_qubits = [q0];
  let control_qubits = [];

  if (canonical === 'CX' || canonical === 'CZ') {
    if (numQubits < 2) return null;
    const target = others[0] ?? (q0 === 0 ? 1 : 0);
    control_qubits = [q0];
    target_qubits = [target];
  } else if (canonical === 'SWAP') {
    if (numQubits < 2) return null;
    const second = others[0] ?? (q0 === 0 ? 1 : 0);
    target_qubits = [q0, second];
  } else if (canonical === 'CCX') {
    if (numQubits < 3) return null;
    control_qubits = [q0, others[0]];
    target_qubits = [others[1]];
  }

  return {
    gate_name: canonical,
    target_qubits,
    control_qubits,
    parameters: meta.has_parameters ? { ...meta.defaultParams } : {},
  };
}
